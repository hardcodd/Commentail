/** Concatenate owned browser modules; no dependencies, transpiler or minifier. */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'frontend/editor');
const languages = ['ru', 'de', 'fr', 'es', 'pt-br'];
const modules = ['markdown.js', 'model.js', 'policy.js', 'shortcuts.js', 'editor.js', 'link-dialog.js', 'url-paste.js', 'mount.js'];
const header = `/* Generated by tools/build_editor.mjs from owned frontend/editor sources. */
(() => {
  'use strict';
  const messages = globalThis.CommentailEditorLocale ?? {};
  const translate = text => messages[text] ?? text;
  const translateChrome = root => {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      const value = node.nodeValue.trim();
      if (value) node.nodeValue = node.nodeValue.replace(value, translate(value));
    }
    for (const node of root.querySelectorAll('[aria-label], [placeholder]')) {
      for (const name of ['aria-label', 'placeholder']) {
        if (node.hasAttribute(name)) node.setAttribute(name, translate(node.getAttribute(name)));
      }
    }
  };
`;
const bundle = header + (await Promise.all(modules.map(name => readFile(path.join(source, name), 'utf8')))).join('\n') + '\n})();\n';
const destination = path.join(root, 'commentail/static/commentail/editor.js');
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== bundle) throw new Error('Editor bundle is stale; run node tools/build_editor.mjs');
} else await writeFile(destination, bundle);
for (const language of languages) {
  const locale = JSON.parse(await readFile(path.join(source, 'locales', language + '.json'), 'utf8'));
  const content = '/* Generated editor locale; loaded only for this page language. */\n' +
    'globalThis.CommentailEditorLocale = Object.freeze(' + JSON.stringify(locale) + ');\n';
  const target = path.join(root, 'commentail/static/commentail', 'editor-' + language + '.js');
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== content) throw new Error('Stale editor locale: ' + language);
  } else await writeFile(target, content);
}
console.log(`Editor bundle: ${Buffer.byteLength(bundle)} bytes`);
